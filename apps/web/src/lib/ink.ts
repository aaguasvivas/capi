// Text ink for a label on a solid color: black or white, whichever has the
// higher WCAG contrast ratio. Used where the fill is a player's avatar color,
// which can be any hex the clients send.

function channel(c: number): number {
  const v = c / 255;
  return v <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4;
}

export function luminance(hex: string): number {
  const m = /^#?([0-9a-f]{6})$/i.exec(hex.trim());
  if (!m) return 0;
  const n = parseInt(m[1], 16);
  return 0.2126 * channel((n >> 16) & 255) + 0.7152 * channel((n >> 8) & 255) + 0.0722 * channel(n & 255);
}

export function contrastRatio(a: string, b: string): number {
  const [hi, lo] = [luminance(a), luminance(b)].sort((x, y) => y - x);
  return (hi + 0.05) / (lo + 0.05);
}

export function inkOn(fill: string): "#000000" | "#ffffff" {
  return contrastRatio("#000000", fill) > contrastRatio("#ffffff", fill) ? "#000000" : "#ffffff";
}
